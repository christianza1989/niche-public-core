import type { NextConfig } from "next";
import path from "node:path";
import {hostingerAssetHeaders} from './lib/hostinger-asset-headers.mjs';

const hostingerNode = process.env.HOSTINGER_NODE_RUNTIME === "1";
const kvapunaikinimasNode = hostingerNode && process.env.HOSTINGER_CANONICAL_HOST === 'kvapunaikinimas.lt';
const hostingerAliases = {
  "cloudflare:workers": "./db/hostinger-node-env.ts",
  "cloudflare:sockets": "./db/hostinger-node-sockets.mjs",
  "cloudflare:email": "./db/hostinger-node-email.mjs",
};
const nextConfig: NextConfig = {
  // Canonical project instructions are maintained in Git, not generated by dev startup.
  agentRules: false,
  headers: async()=>hostingerNode?hostingerAssetHeaders():[],
  images: kvapunaikinimasNode?{
    formats:['image/avif','image/webp'],
    imageSizes:[300,500],
    qualities:[85],
    minimumCacheTTL:31536000,
    localPatterns:[{pathname:'/content-assets/kvapunaikinimas/*.webp',search:''}],
    remotePatterns:[],
  }:undefined,
  webpack: (config, context) => {
    if (hostingerNode) {
      const {webpack}=context;
      config.resolve ??= {};
      config.resolve.alias = { ...config.resolve.alias, ...hostingerAliases };
      config.plugins ??= [];
      config.plugins.push(new webpack.NormalModuleReplacementPlugin(/^cloudflare:(workers|sockets|email)$/, (resource:{request:string})=>{
        resource.request=path.resolve(process.cwd(),hostingerAliases[resource.request as keyof typeof hostingerAliases]);
      }));
    } else if (process.env.CLOUDFLARE_WORKER_BUILD !== "1") {
      config.resolve ??= {};
      config.resolve.alias ??= {};
      config.resolve.alias["cloudflare:workers"] = "./db/vercel-cloudflare-workers-stub.ts";
    }
    return config;
  },
  turbopack: {
    resolveAlias: hostingerNode ? hostingerAliases : process.env.CLOUDFLARE_WORKER_BUILD === "1" ? {} : {
      "cloudflare:workers": "./db/vercel-cloudflare-workers-stub.ts",
    },
  },
};

export default nextConfig;
